//! Standalone Rust source backend. Nether's checked MIR owns lifetime semantics;
//! generated raw places do not introduce Rust reference aliasing assumptions.
use crate::{
    hir::{self, Type, Value},
    mir::{self, *},
};
use nether_frontend::source::{Diagnostic, Source};
use nether_semantics::OverflowChecks;
mod classes;
mod lifecycle;
mod operations;
mod stack;
mod structured;

pub fn emit(program: &hir::Program, checks: OverflowChecks) -> Result<String, Diagnostic> {
    emit_with_sources(program, checks, &[])
}
pub fn emit_with_sources(
    program: &hir::Program,
    checks: OverflowChecks,
    sources: &[Source],
) -> Result<String, Diagnostic> {
    let active = structured::candidates(program, checks);
    emit_internal(
        &mir::lower(program),
        checks,
        sources,
        Some((program, &active)),
    )
}
pub fn emit_mir(program: &Program, checks: OverflowChecks) -> Result<String, Diagnostic> {
    emit_mir_with_sources(program, checks, &[])
}
pub fn emit_mir_with_sources(
    program: &Program,
    checks: OverflowChecks,
    sources: &[Source],
) -> Result<String, Diagnostic> {
    emit_internal(program, checks, sources, None)
}
fn emit_internal(
    program: &Program,
    checks: OverflowChecks,
    sources: &[Source],
    structured: Option<(&hir::Program, &std::collections::BTreeSet<usize>)>,
) -> Result<String, Diagnostic> {
    mir::verify::verify(program)?;
    let mut emitter = Emitter {
        types: Vec::new(),
        checks,
        destructors: program.destructors.clone(),
        resources: false,
        stack_slots: Default::default(),
        classes: program.classes.clone(),
    };
    for f in &program.functions {
        emitter.register(&f.result);
        for local in &f.locals {
            emitter.register(&local.ty);
        }
    }
    emitter.resources = emitter.types.iter().any(|t| emitter.resource(t));
    let mut out = String::from("// Generated by Nether. Ownership was checked before lowering.\n#![allow(dead_code, unused_variables, unused_mut, unused_parens, unreachable_code, non_snake_case)]\nuse std::mem::{MaybeUninit, ManuallyDrop};\n#[derive(Clone, Copy, Debug)]\nstruct Fault { file: &'static str, line: usize, column: usize }\n");
    out.push_str("#[cfg(not(target_pointer_width = \"64\"))] compile_error!(\"Nether currently requires a 64-bit target\");\n");
    for (id, ty) in emitter.types.iter().enumerate() {
        match ty {
            Type::Record { fields, .. } => {
                out.push_str(&format!("#[repr(C)] struct T{id} {{"));
                for (i, field) in fields.iter().enumerate() {
                    out.push_str(&format!("f{i}: {},", emitter.ty(&field.ty)));
                }
                out.push_str("}\n");
            }
            Type::Tuple(fields) => {
                out.push_str(&format!("#[repr(C)] struct T{id} {{"));
                for (i, field) in fields.iter().enumerate() {
                    out.push_str(&format!("f{i}: {},", emitter.ty(field)));
                }
                out.push_str("}\n");
            }
            Type::Enum { variants, .. } => {
                out.push_str(&format!("#[repr(C)] struct T{id} {{ tag: u32, data: U{id} }}\n#[repr(C)] union U{id} {{"));
                for (i, variant) in variants.iter().enumerate() {
                    out.push_str(&format!(
                        "v{i}: ManuallyDrop<{}>,",
                        emitter.ty(&Type::Tuple(variant.fields.clone()))
                    ));
                }
                if variants.is_empty() {
                    out.push_str("empty: (),");
                }
                out.push_str("}\n");
            }
            _ => {}
        }
    }
    if emitter.resources {
        out.push_str(&emitter.lifecycle_types());
        out.push_str(&emitter.class_copies());
    }
    let stack_eligible = checks == OverflowChecks::Wrapping && stack::eligible(program);
    for (id, f) in program.functions.iter().enumerate() {
        emitter.stack_slots = if stack_eligible {
            stack::slots(f)
        } else {
            Default::default()
        };
        out.push_str(&format!("unsafe fn f{id}("));
        if emitter.resources {
            out.push_str("ctx:&mut Context,");
        }
        for (i, local) in f.parameters.iter().enumerate() {
            out.push_str(&format!(
                "a{i}: {},",
                emitter.local_ty(&f.locals[*local], false)
            ));
        }
        out.push_str(&format!(
            ") -> Result<{}, Fault> {{\n",
            emitter.return_ty(f)
        ));
        if structured.is_some_and(|(_, active)| active.contains(&id)) {
            let args = (0..f.parameters.len())
                .map(|i| format!("a{i}"))
                .collect::<Vec<_>>()
                .join(",");
            out.push_str(&format!("Ok(fast{id}({args})) }}\n"));
            continue;
        }
        for (i, local) in f.locals.iter().enumerate() {
            out.push_str(&format!(
                "let mut storage{i} = MaybeUninit::<{}>::uninit();\nlet l{i} = std::ptr::addr_of_mut!(storage{i}).cast::<{}>();\n",
                emitter.local_ty(local, emitter.captured_slot(f, i)), emitter.local_ty(local, emitter.captured_slot(f, i))
            ));
        }
        for local in &emitter.stack_slots {
            let ty = emitter.type_id(&f.locals[*local].ty);
            out.push_str(&format!("// nonescaping frame allocation\nlet mut frame{local}=MaybeUninit::<H{ty}>::uninit();\n"));
        }
        for (i, local) in f.parameters.iter().enumerate() {
            out.push_str(&format!("l{local}.write(a{i});\n"));
        }
        if emitter.resources {
            out.push_str(&emitter.storage(f));
        }
        out.push_str(&format!(
            "let mut pending: Option<Fault> = None;\nlet mut pc = {}usize;\nloop {{ match pc {{\n",
            f.entry
        ));
        let mut predecessors = vec![0; f.blocks.len()];
        let mut leaders = vec![false; f.blocks.len()];
        leaders[f.entry] = true;
        for block in &f.blocks {
            for next in block.terminator.successors() {
                predecessors[next] += 1;
            }
            match &block.terminator {
                Terminator::Branch { yes, no, .. } => {
                    leaders[*yes] = true;
                    leaders[*no] = true;
                }
                Terminator::Evaluate { unwind, .. } | Terminator::CheckPlace { unwind, .. } => {
                    leaders[*unwind] = true
                }
                _ => {}
            }
        }
        for (id, count) in predecessors.iter().enumerate() {
            leaders[id] |= *count != 1;
        }
        // Fuse straight-line MIR blocks, so arithmetic and storage boundaries
        // do not each incur a generated control-flow dispatch.
        for leader in 0..f.blocks.len() {
            if !leaders[leader] {
                continue;
            }
            out.push_str(&format!("{leader} => {{\n"));
            let mut block_id = leader;
            loop {
                let block = &f.blocks[block_id];
                let (file, line, column) = sources
                    .get(block.span.source.0)
                    .map(|s| {
                        let (line, column) = s.location(block.span.start).unwrap_or((0, 0));
                        (s.name.as_str(), line, column)
                    })
                    .unwrap_or(("<source>", 0, 0));
                out.push_str(&format!(
                    "let fault = Fault {{ file: {file:?}, line: {line}, column: {column} }};\n"
                ));
                match &block.terminator {
                    Terminator::EndStorage { locals, .. } => {
                        if emitter.resources {
                            out.push_str(&emitter.end_storage(locals, f));
                        }
                    }
                    Terminator::Goto(_) => {}
                    Terminator::Branch { condition, yes, no } => out.push_str(&format!(
                        "pc = if {} {{ {yes} }} else {{ {no} }};\n",
                        emitter.operand(condition)
                    )),
                    Terminator::Return(value) => {
                        if emitter.resources {
                            if let Operand::Local(id) = value {
                                out.push_str(&emitter.forget(&Place::local(*id), f));
                            }
                        }
                        out.push_str(&format!(
                            "return Ok({});\n",
                            match value {
                                Operand::Address(place) => emitter.view(place, f),
                                _ => emitter.operand(value),
                            }
                        ))
                    }
                    Terminator::ResumePanic => {
                        out.push_str("return Err(pending.expect(\"invalid panic edge\"));\n")
                    }
                    Terminator::Unreachable => {
                        out.push_str("unreachable!(\"invalid Nether control flow\");\n")
                    }
                    Terminator::CheckPlace {
                        place,
                        next: _,
                        unwind,
                    } => {
                        let (address, _) = emitter.place(place, f);
                        let raise = if emitter.resources {
                            "ctx.raise();"
                        } else {
                            ""
                        };
                        out.push_str(&format!("let result: Result<(), Fault> = (|| {{ let _ = {address}; Ok(()) }})();\nif let Err(e) = result {{ {raise}pending = Some(e); pc = {unwind}; continue; }}\n"));
                    }
                    Terminator::Evaluate {
                        operation,
                        destination,
                        next: _,
                        unwind,
                    } => {
                        if emitter.resources {
                            out.push_str(&emitter.evaluate_resource(
                                operation,
                                destination,
                                f,
                                *unwind,
                            ));
                        } else {
                            let (dest, ty) = emitter.place(destination, f);
                            let expression = emitter.operation(operation, &ty, f);
                            out.push_str(&format!("let result: Result<(), Fault> = (|| {{ let value = {expression}; ({dest}).write(value); Ok(()) }})();\nif let Err(e) = result {{ pending = Some(e); pc = {unwind}; continue; }}\n"));
                        }
                    }
                }
                let next = match &block.terminator {
                    Terminator::Evaluate { next, .. }
                    | Terminator::CheckPlace { next, .. }
                    | Terminator::Goto(next)
                    | Terminator::EndStorage { next, .. } => Some(*next),
                    _ => None,
                };
                match next {
                    Some(next) if !leaders[next] => block_id = next,
                    Some(next) => {
                        out.push_str(&format!("pc = {next};\n"));
                        break;
                    }
                    None => break,
                }
            }
            out.push_str("}\n");
        }
        out.push_str("_ => unreachable!(\"invalid Nether block\"),\n} } }\n");
    }
    if let Some((hir, active)) = structured {
        out.push_str(&structured::emit(hir, active));
    }
    if let Some(id) = program.main {
        let result = if program.functions[id].result == Type::Unit {
            "0"
        } else {
            "value"
        };
        let context = if emitter.resources {
            "&mut Context {clock:0,panicking:false}"
        } else {
            ""
        };
        out.push_str(&format!("fn main() {{ let code = match unsafe {{ f{id}({context}) }} {{ Ok(value) => {result}, Err(e) => {{ eprintln!(\"{{}}:{{}}:{{}}: Nether panic\", e.file, e.line, e.column); 101 }} }}; std::process::exit(code); }}\n"));
    }
    Ok(out)
}
struct Emitter {
    types: Vec<Type>,
    checks: OverflowChecks,
    destructors: mir::drop_plan::Destructors,
    resources: bool,
    stack_slots: std::collections::BTreeSet<usize>,
    classes: hir::Classes,
}
impl Emitter {
    fn class_payload(&self, name: &str) -> Type {
        Type::Record {
            name: format!("<payload {name}>"),
            copy: false,
            fields: self.classes[name].fields.clone(),
        }
    }
    fn register(&mut self, ty: &Type) {
        if self.types.contains(ty) {
            return;
        }
        self.types.push(ty.clone());
        match ty {
            Type::Class { .. } => self.register(&self.class_payload(&ty.class_key())),
            Type::Record { fields, .. } => {
                for f in fields {
                    self.register(&f.ty);
                }
            }
            Type::Enum { variants, .. } => {
                for v in variants {
                    self.register(&Type::Tuple(v.fields.clone()));
                }
            }
            Type::Tuple(fields) => {
                for t in fields {
                    self.register(t);
                }
            }
            Type::Array(t, _) | Type::StoredView(t) | Type::Pointer { pointee: t, .. } => {
                self.register(t)
            }
            Type::Function {
                parameters, result, ..
            } => {
                for (_, t) in parameters {
                    self.register(t);
                }
                self.register(result);
            }
            _ => {}
        }
    }
    fn ty(&self, ty: &Type) -> String {
        match ty {
            Type::Pointer { mutable, pointee } => format!(
                "*{} {}",
                if *mutable { "mut" } else { "const" },
                self.ty(pointee)
            ),
            Type::StoredView(target) => {
                if self.resource(target) {
                    format!("V{}", self.type_id(target))
                } else {
                    format!("*mut {}", self.ty(target))
                }
            }
            Type::Class { .. } => {
                format!("*mut H{}", self.types.iter().position(|t| t == ty).unwrap())
            }
            Type::Unit => "()".into(),
            Type::Bool => "bool".into(),
            Type::Char => "char".into(),
            Type::Str => "&'static str".into(),
            Type::F32 => "f32".into(),
            Type::F64 => "f64".into(),
            Type::Integer(t) => format!("{t:?}").to_lowercase(),
            Type::Record { .. } | Type::Enum { .. } | Type::Tuple(_) => {
                format!("T{}", self.types.iter().position(|t| t == ty).unwrap())
            }
            Type::Array(element, count) => format!("[{}; {count}]", self.ty(element)),
            Type::Function {
                parameters,
                result,
                contract,
                ..
            } => format!(
                "unsafe fn({}{}) -> Result<{}, Fault>",
                if self.resources { "&mut Context," } else { "" },
                parameters
                    .iter()
                    .enumerate()
                    .map(|(i, (_, ty))| {
                        // Without a known entry, non-Copy parameters are borrowed.
                        if contract
                            .as_ref()
                            .map_or(!ty.copyable(), |c| c.modes[i].is_some())
                        {
                            self.borrow_ty(ty)
                        } else {
                            self.ty(ty)
                        }
                    })
                    .collect::<Vec<_>>()
                    .join(","),
                if contract.as_ref().is_some_and(|c| c.view.is_some()) {
                    self.borrow_ty(result)
                } else {
                    self.ty(result)
                }
            ),
        }
    }
    fn borrow_ty(&self, ty: &Type) -> String {
        if self.resource(ty) {
            format!("V{}", self.type_id(ty))
        } else {
            format!("*mut {}", self.ty(ty))
        }
    }
    fn captured_slot(&self, f: &Function, local: usize) -> bool {
        f.blocks.iter().any(|b| matches!(&b.terminator, Terminator::Evaluate {operation:Operation::CapturePlace(_),destination,..} if destination.local==local))
    }
    fn return_ty(&self, f: &Function) -> String {
        if f.result_view.is_some() {
            if self.resource(&f.result) {
                format!(
                    "V{}",
                    self.types.iter().position(|t| t == &f.result).unwrap()
                )
            } else {
                format!("*mut {}", self.ty(&f.result))
            }
        } else {
            self.ty(&f.result)
        }
    }
    fn local_ty(&self, local: &hir::Local, capture: bool) -> String {
        if capture && matches!(local.ty, Type::Class { .. }) {
            return format!(
                "W{}",
                self.types.iter().position(|t| t == &local.ty).unwrap()
            );
        }
        if local.view.is_some() && self.resource(&local.ty) {
            format!(
                "V{}",
                self.types.iter().position(|t| t == &local.ty).unwrap()
            )
        } else if local.view.is_some() {
            format!("*mut {}", self.ty(&local.ty))
        } else {
            self.ty(&local.ty)
        }
    }
    fn constant(&self, value: &Value) -> String {
        match value {
            Value::Unit => "()".into(),
            Value::Bool(v) => v.to_string(),
            Value::Char(v) => format!("{v:?}"),
            Value::Integer(v) => {
                format!("({}u128 as {})", v.bits(), self.ty(&Type::Integer(v.ty())))
            }
            Value::F32(v) => format!("f32::from_bits({})", v.to_bits()),
            Value::F64(v) => format!("f64::from_bits({})", v.to_bits()),
            Value::Str(v) => format!("{v:?}"),
            Value::Function(id) => format!("f{id}"),
            _ => unreachable!("aggregate constants must be lowered to construction"),
        }
    }
    fn aggregate(&self, values: &[String], ty: &Type) -> String {
        match ty {
            Type::Array(_, _) => format!("[{}]", values.join(",")),
            Type::Unit => "()".into(),
            _ => format!(
                "{} {{ {} }}",
                self.ty(ty),
                values
                    .iter()
                    .enumerate()
                    .map(|(i, v)| format!("f{i}: {v},"))
                    .collect::<String>()
            ),
        }
    }
    fn enum_value(&self, variant: usize, values: &[String], ty: &Type) -> String {
        let id = self.types.iter().position(|t| t == ty).unwrap();
        let Type::Enum { variants, .. } = ty else {
            unreachable!()
        };
        let payload = self.aggregate(values, &Type::Tuple(variants[variant].fields.clone()));
        format!("T{id} {{ tag: {variant}, data: U{id} {{ v{variant}: ManuallyDrop::new({payload}) }} }}")
    }
    fn typed_constant(&self, value: &Value, ty: &Type) -> String {
        match value {
            Value::Aggregate(values) => {
                let fields = match ty {
                    Type::Array(element, _) => vec![(**element).clone(); values.len()],
                    Type::Tuple(fields) => fields.clone(),
                    Type::Record { fields, .. } => fields.iter().map(|f| f.ty.clone()).collect(),
                    _ => unreachable!(),
                };
                self.aggregate(
                    &values
                        .iter()
                        .zip(fields)
                        .map(|(v, t)| self.typed_constant(v, &t))
                        .collect::<Vec<_>>(),
                    ty,
                )
            }
            Value::Enum { variant, fields } => {
                let Type::Enum { variants, .. } = ty else {
                    unreachable!()
                };
                self.enum_value(
                    *variant,
                    &fields
                        .iter()
                        .zip(&variants[*variant].fields)
                        .map(|(v, t)| self.typed_constant(v, t))
                        .collect::<Vec<_>>(),
                    ty,
                )
            }
            _ => self.constant(value),
        }
    }
    fn operand(&self, value: &Operand) -> String {
        match value {
            Operand::Local(id) => format!("l{id}.read()"),
            Operand::Constant(v) => self.constant(v),
            Operand::Address(_) => unreachable!("address operand requires function context"),
        }
    }
    fn operand_ty(&self, value: &Operand, f: &Function) -> Type {
        match value {
            Operand::Local(id) => f.locals[*id].ty.clone(),
            Operand::Address(p) => self.place(p, f).1,
            Operand::Constant(v) => match v {
                Value::Integer(v) => Type::Integer(v.ty()),
                Value::Bool(_) => Type::Bool,
                Value::F32(_) => Type::F32,
                Value::F64(_) => Type::F64,
                Value::Char(_) => Type::Char,
                Value::Str(_) => Type::Str,
                Value::Unit => Type::Unit,
                _ => unreachable!(),
            },
        }
    }
    fn place(&self, place: &Place, f: &Function) -> (String, Type) {
        let mut ty = f.locals[place.local].ty.clone();
        let mut address = format!("l{}", place.local);
        for p in &place.projections {
            match p {
                Projection::Dereference => {
                    address =
                        if matches!(ty, Type::Class { .. }) && !self.captured_slot(f, place.local) {
                            format!("std::ptr::addr_of_mut!((*({address})).data)")
                        } else if self.resource(&ty) {
                            format!("({address}).read().data")
                        } else {
                            format!("({address}).read()")
                        }
                }
                Projection::Field(i) => {
                    if let Type::Class { .. } = &ty {
                        address = format!(
                            "std::ptr::addr_of_mut!((*({address}).read()).data).cast::<{}>()",
                            self.ty(&self.class_payload(&ty.class_key()))
                        );
                    }
                    let (field, field_ty) = match &ty {
                        Type::Class { .. } => (
                            format!("f{i}"),
                            self.classes[&ty.class_key()].fields[*i].ty.clone(),
                        ),
                        Type::Record { fields, .. } => (format!("f{i}"), fields[*i].ty.clone()),
                        Type::Tuple(fields) => (format!("f{i}"), fields[*i].clone()),
                        _ => unreachable!(),
                    };
                    address = format!("std::ptr::addr_of_mut!((*({address})).{field})");
                    ty = field_ty;
                }
                Projection::Variant(i) => {
                    let Type::Enum { variants, .. } = &ty else {
                        unreachable!()
                    };
                    ty = Type::Tuple(variants[*i].fields.clone());
                    address = format!(
                        "std::ptr::addr_of_mut!((*({address})).data.v{i}).cast::<{}>()",
                        self.ty(&ty)
                    );
                }
                Projection::Index(_) | Projection::ConstantIndex(_) => {
                    let Type::Array(element, count) = &ty else {
                        unreachable!()
                    };
                    let index = match p {
                        Projection::Index(id) => format!("l{id}.read()"),
                        Projection::ConstantIndex(n) => format!("{n}usize"),
                        _ => unreachable!(),
                    };
                    address = format!("{{ let index = {index}; if index >= {count} {{ return Err(fault); }} ({address}).cast::<{}>().add(index) }}", self.ty(element));
                    ty = (**element).clone();
                }
            }
        }
        (address, ty)
    }
}
